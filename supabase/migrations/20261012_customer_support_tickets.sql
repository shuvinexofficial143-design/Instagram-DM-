-- Customer support inbox, manual refund/cancellation requests, and threaded replies.
-- SECURITY: no browser/Data API access. Every operation is authorized in /api/support
-- with a verified Supabase JWT; the server alone uses the service-role key.
-- No changes to payment orders, entitlements or existing Instagram automations.

create table if not exists public.autoreply_support_tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity unique,
  owner_user_id text not null,
  ticket_type text not null check (ticket_type in ('general','technical','payment','refund','cancellation','account_deletion')),
  subject text not null check (char_length(subject) between 4 and 160),
  reason text not null default '',
  order_id text,
  status text not null default 'open' check (status in ('open','in_review','waiting_customer','resolved','closed','approved','rejected','refund_initiated','refunded')),
  admin_note text,
  last_message_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists autoreply_support_tickets_owner_idx on public.autoreply_support_tickets(owner_user_id, created_at desc);
create index if not exists autoreply_support_tickets_admin_idx on public.autoreply_support_tickets(status, last_message_at desc);
create index if not exists autoreply_support_tickets_order_idx on public.autoreply_support_tickets(owner_user_id, order_id) where order_id is not null;

create table if not exists public.autoreply_support_messages (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.autoreply_support_tickets(id) on delete cascade,
  sender_user_id text not null,
  sender_role text not null check (sender_role in ('customer','support')),
  body text not null check (char_length(body) between 1 and 5000),
  created_at timestamptz not null default now()
);
create index if not exists autoreply_support_messages_thread_idx on public.autoreply_support_messages(ticket_id, created_at asc);

alter table public.autoreply_support_tickets enable row level security;
alter table public.autoreply_support_messages enable row level security;
revoke all on public.autoreply_support_tickets from public, anon, authenticated;
revoke all on public.autoreply_support_messages from public, anon, authenticated;
revoke all on sequence public.autoreply_support_tickets_ticket_number_seq from public, anon, authenticated;
grant select, insert, update, delete on public.autoreply_support_tickets to service_role;
grant select, insert, update, delete on public.autoreply_support_messages to service_role;
grant usage, select on sequence public.autoreply_support_tickets_ticket_number_seq to service_role;

comment on table public.autoreply_support_tickets is 'Private support cases and refund/cancellation applications. Does not cancel plans or initiate payouts.';
comment on table public.autoreply_support_messages is 'Private threaded support messages, readable only through authorized server API.';
